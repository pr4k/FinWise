// Keep the supplied modules isolated from the application's global bindings.
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const source=name=>fs.readFileSync(path.join(root,'finwise-planner',name),'utf8');
const modules=['planner.js','card-planner.js','card-reserves.js','planner-calendar.js'].map(name=>`// ${name}\n${source(name)}`).join('\n');
fs.writeFileSync(path.join(root,'web/planner.js'),'// Generated by node scripts/build-planner.cjs; edit finwise-planner sources.\n'+source('host.js').replace('/* PLANNER_MODULES */',()=>modules));
fs.writeFileSync(path.join(root,'web/planner.css'),source('planner.css').replace(/([^{}]+)\{/g,(rule,selectors)=>selectors.trim().startsWith('@')?rule:selectors.split(',').map(selector=>'.planner-module '+selector.trim()).join(',')+'{')+'\n'+source('theme.css'));
